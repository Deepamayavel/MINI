// In-memory cache for dynamic translations
const dynamicTranslationCache = new Map();

// Dynamic translation fallback using Google Translate single API
export const translateDynamicAsync = async (text, targetLangShortCode) => {
  if (!text || !targetLangShortCode || targetLangShortCode === 'en') {
    return text;
  }
  const cacheKey = `${targetLangShortCode}:::${text}`;
  if (dynamicTranslationCache.has(cacheKey)) {
    return dynamicTranslationCache.get(cacheKey);
  }

  try {
    const url = `https://translate.googleapis.com/translate_a/single?client=gtx&sl=en&tl=${targetLangShortCode}&dt=t&q=${encodeURIComponent(text)}`;
    const controller = new AbortController();
    const timeoutId = setTimeout(() => controller.abort(), 2500);

    const res = await fetch(url, { signal: controller.signal });
    clearTimeout(timeoutId);

    if (res.ok) {
      const data = await res.json();
      if (Array.isArray(data) && Array.isArray(data[0])) {
        const translated = data[0].map(item => item[0]).join('').trim();
        if (translated) {
          dynamicTranslationCache.set(cacheKey, translated);
          return translated;
        }
      }
    }
  } catch (err) {
    // Silently fall back to original text if offline
  }

  return text;
};

// Main function to translate a medical term (disease, specialist, test, precaution)
export const translateMedicalTerm = (term = '', targetLang = 'en-IN') => {
  if (!term) return '';
  const shortCode = LANG_SHORT_CODES[targetLang] || 'en';
  if (shortCode === 'en') return term;

  const trimmed = term.trim();

  // 1. Check Disease dict
  if (DISEASE_TRANSLATIONS[shortCode] && DISEASE_TRANSLATIONS[shortCode][trimmed]) {
    return DISEASE_TRANSLATIONS[shortCode][trimmed];
  }
  // Check case-insensitive disease match
  if (DISEASE_TRANSLATIONS[shortCode]) {
    for (const [key, val] of Object.entries(DISEASE_TRANSLATIONS[shortCode])) {
      if (key.toLowerCase() === trimmed.toLowerCase()) {
        return val;
      }
    }
  }

  // 2. Check Specialist dict
  if (SPECIALIST_TRANSLATIONS[shortCode] && SPECIALIST_TRANSLATIONS[shortCode][trimmed]) {
    return SPECIALIST_TRANSLATIONS[shortCode][trimmed];
  }
  if (SPECIALIST_TRANSLATIONS[shortCode]) {
    for (const [key, val] of Object.entries(SPECIALIST_TRANSLATIONS[shortCode])) {
      if (key.toLowerCase() === trimmed.toLowerCase()) {
        return val;
      }
    }
  }

  // 3. Check Test dict
  if (TEST_TRANSLATIONS[shortCode] && TEST_TRANSLATIONS[shortCode][trimmed]) {
    return TEST_TRANSLATIONS[shortCode][trimmed];
  }
  if (TEST_TRANSLATIONS[shortCode]) {
    for (const [key, val] of Object.entries(TEST_TRANSLATIONS[shortCode])) {
      if (key.toLowerCase() === trimmed.toLowerCase()) {
        return val;
      }
    }
  }

  // 4. Check Precaution dict
  if (PRECAUTION_TRANSLATIONS[shortCode] && PRECAUTION_TRANSLATIONS[shortCode][trimmed]) {
    return PRECAUTION_TRANSLATIONS[shortCode][trimmed];
  }
  if (PRECAUTION_TRANSLATIONS[shortCode]) {
    for (const [key, val] of Object.entries(PRECAUTION_TRANSLATIONS[shortCode])) {
      if (key.toLowerCase() === trimmed.toLowerCase()) {
        return val;
      }
    }
  }

  // Return dynamic cached item if available
  const cacheKey = `${shortCode}:::${trimmed}`;
  if (dynamicTranslationCache.has(cacheKey)) {
    return dynamicTranslationCache.get(cacheKey);
  }

  return trimmed;
};

// Translate Triage Badge Label
export const translateTriageLabel = (label = '', targetLang = 'en-IN') => {
  const shortCode = LANG_SHORT_CODES[targetLang] || 'en';
  if (shortCode === 'en') return label;

  const ui = UI_TRANSLATIONS[shortCode];
  if (!ui) return label;

  if (/urgent|severe|emergency/i.test(label)) {
    return ui.urgentCare || label;
  }
  if (/24-48|moderate|doctor/i.test(label)) {
    return ui.moderateCare || label;
  }
  if (/mild|home|routine|primary/i.test(label)) {
    return ui.mildCare || label;
  }
  return label;
};

