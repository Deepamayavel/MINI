// Automatic input language detector based on script unicode ranges and keywords
export const detectInputLanguage = (text = '', preferredLang = 'en-IN') => {
  const t = text || '';

  // 1. Check Tamil unicode range
  if (/[\u0B80-\u0BFF]/.test(t)) {
    return 'ta-IN';
  }
  // 2. Check Devanagari (Hindi) unicode range
  if (/[\u0900-\u097F]/.test(t)) {
    return 'hi-IN';
  }
  // 3. Check Telugu unicode range
  if (/[\u0C00-\u0C7F]/.test(t)) {
    return 'te-IN';
  }
  // 4. Check Arabic unicode range
  if (/[\u0600-\u06FF]/.test(t)) {
    return 'ar-SA';
  }

  // 5. If user specifically selected a non-English language in dropdown, respect that
  if (preferredLang && preferredLang !== 'en-IN' && preferredLang !== 'en-US') {
    return preferredLang;
  }

  // 6. Check common Romance/European language markers
  const lower = t.toLowerCase();
  if (/[áéíóúñ¿¡]/.test(lower) || /\b(tengo|fiebre|dolor|cabeza|pecho|tos|vomitos|garganta|cansancio)\b/i.test(lower)) {
    return 'es-ES';
  }
  if (/[àâçèêëîïôûù]/.test(lower) || /\b(j'ai|fievre|fièvre|toux|douleur|gorge|poitrine|fatigue)\b/i.test(lower)) {
    return 'fr-FR';
  }
  if (/[äöüß]/.test(lower) || /\b(ich|habe|fieber|husten|schmerzen|kopf|brust|hals)\b/i.test(lower)) {
    return 'de-DE';
  }

  return preferredLang || 'en-IN';
};

