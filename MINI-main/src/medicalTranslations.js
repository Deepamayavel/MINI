// Helper to get Dashboard Translations for any language code
export const getDashboardLabels = (targetLang = 'en-IN') => {
  const shortCode = LANG_SHORT_CODES[targetLang] || 'en';
  return DASHBOARD_TRANSLATIONS[shortCode] || DASHBOARD_TRANSLATIONS.en;
};

// Helper to get Localized Health Tip
export const getTranslatedHealthTip = (tipIndex, defaultTips, targetLang = 'en-IN') => {
  const shortCode = LANG_SHORT_CODES[targetLang] || 'en';
  const localizedList = TRANSLATED_HEALTH_TIPS[shortCode];
  if (localizedList && localizedList[tipIndex % localizedList.length]) {
    return localizedList[tipIndex % localizedList.length];
  }
  return defaultTips[tipIndex % defaultTips.length];
};

